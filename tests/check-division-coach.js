// Regression checks for the coach's question order and child-supplied working.
const fs = require('fs'), path = require('path'), vm = require('vm'), assert = require('assert');
const ctx = {}; vm.createContext(ctx);
for (const name of ['longdiv', 'division-coach']) vm.runInContext(fs.readFileSync(path.join(__dirname, '../public/js/' + name + '.js'), 'utf8'), ctx);
const make = (n, d) => ctx.DivisionCoach.create(n, d);
const c = make(228, 3);
assert.strictEqual(c.view().help, false);
assert(!/22|76|\b7\b/.test(c.view().text), 'initial prompt exposes working');
assert.strictEqual(c.submit('1').status, 'wrong');
assert(c.view().text.includes('Can 3 go into 2?'));
assert(!c.view().text.includes('22'), 'next group exposed before No');
assert.strictEqual(c.yesNo(true).status, 'wrong');
assert(c.view().text.includes('Can 3 go into 2?'));
assert.strictEqual(c.yesNo(false).status, 'support');
assert(c.view().text.includes("Let's take 22"));
assert.strictEqual(c.submit('7').status, 'wait', 'numeric answer bypassed Yes/No');
assert.strictEqual(c.yesNo(true).status, 'support');
assert(c.view().text.includes('How many groups of 3 fit into 22?'));
assert.strictEqual(c.submit('1').status, 'wrong');
assert(c.view().text.includes('1 × 3'));
assert.strictEqual(c.submit('3').status, 'support');
assert.strictEqual(c.yesNo(true).status, 'support');
assert(c.view().text.includes('one more group'));
assert.strictEqual(c.yesNo(false).status, 'wrong');
assert.strictEqual(c.yesNo(true).status, 'support');
assert.strictEqual(c.submit('7').status, 'right');
assert.strictEqual(c.step().phase, 'multiply');
assert.strictEqual(c.submit('20').status, 'wrong');
for (const total of [3, 6, 9, 12, 15, 18]) assert.strictEqual(c.submit(String(total)).status, 'support');
assert.strictEqual(c.submit('21').status, 'right');
assert.strictEqual(c.submit('0').status, 'wrong');
assert.strictEqual(c.yesNo(true).status, 'support');
assert(c.view().text.includes('Count up from 21 to 22'));
assert.strictEqual(c.submit('1').status, 'right');
assert.strictEqual(c.submit('0').status, 'wrong');
assert.strictEqual(c.view().annotation.down, true);
assert.strictEqual(c.submit('8').status, 'right');
for (const answer of ['6', '18', '0']) assert.strictEqual(c.submit(answer).status, 'right');
assert.strictEqual(c.view().done, true);
for (const [n, d] of [[380,7], [101,2], [100,99], [432,15], [999,99], [7,8], [100,2]]) {
  const m = make(n,d);
  while (m.step()) { const s = m.step(); assert.strictEqual(m.submit(s.answer).status, 'right'); }
  assert.strictEqual(m.view().done, true);
}
// Guided multiplication with a zero quotient digit must ask for zero groups.
const z = make(101, 2);
while (!(z.step().phase === 'multiply' && z.step().digit === 0)) z.submit(z.step().answer);
assert.strictEqual(z.submit('1').status, 'wrong');
assert(z.view().text.includes('Zero groups'));
assert.strictEqual(z.submit('0').status, 'right');
const high = make(228, 3);
high.submit('9'); high.yesNo(false); high.yesNo(true);
assert.strictEqual(high.submit('9').status, 'wrong');
assert.strictEqual(high.submit('27').status, 'support');
assert.strictEqual(high.yesNo(false).status, 'support');
assert(high.view().feedback.includes('fewer'));
assert.strictEqual(high.submit('7').status, 'right');
const done = make(12, 3);
while (done.step()) done.submit(done.step().answer);
done.requestHelp();
assert(done.view().text.includes('Read the quotient digits'));
assert(!done.view().text.includes('4'), 'final-answer support exposed the answer');
assert.strictEqual(ctx.DivisionCoach.readNumber('.5'), .5);
assert.strictEqual(ctx.DivisionCoach.readNumber('7.0'), 7);
assert.strictEqual(ctx.DivisionCoach.readNumber('7..0'), null);
assert.strictEqual(ctx.DivisionCoach.readNumber('.'), null);
// The child may write the quotient and product before checking either row.
const batch = make(498, 8);
batch.requestHelp(); batch.yesNo(false); batch.yesNo(true);
const checkedRows = batch.submitRows([{ row: 0, raw: '6' }, { row: 2, raw: '48' }]);
assert.deepStrictEqual(Array.from(checkedRows, r => r.status), ['right', 'right']);
assert.strictEqual(batch.step().phase, 'subtract');
assert.strictEqual(batch.step().current, 49);
assert.strictEqual(batch.step().product, 48);
const partial = make(498, 8);
const partiallyChecked = partial.submitRows([{ row: 7, raw: '6' }, { row: 0, raw: '47' }, { row: 4, raw: '1' }]);
assert.deepStrictEqual(Array.from(partiallyChecked, r => r.status), ['right', 'wrong']);
assert.strictEqual(partial.step().phase, 'multiply');
assert.strictEqual(partial.submit('48').status, 'right', 'a correct product must remain usable during coaching');
assert.strictEqual(partial.step().phase, 'subtract');
const waiting = make(498, 8);
waiting.requestHelp();
assert.strictEqual(waiting.submitRows([{ row: 0, raw: '6' }]).length, 0, 'row batching bypassed the Yes/No question');
console.log('ALL PASSED: staged fit questions, trial multiples, multiplication, subtraction, bring-down, zeros, decimals, multi-row working, and direct solving.');
