// Build only the public app. GitHub Pages has no Cloudflare Functions runtime.
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const root=path.resolve(__dirname,'..'),source=path.join(root,'public'),output=path.join(root,'dist');
if(path.relative(root,output)!=='dist')throw Error('Unexpected output path');
if(fs.existsSync(output)){
  if(path.relative(root,fs.realpathSync(output))!=='dist'||!fs.existsSync(path.join(output,'.brain-teaser-build')))throw Error('Refusing to replace an unrecognised output folder');
  fs.rmSync(output,{recursive:true});
}
fs.cpSync(source,output,{recursive:true});
fs.writeFileSync(path.join(output,'.brain-teaser-build'),'Generated by scripts/build-pages.js\n');
let html=fs.readFileSync(path.join(source,'index.html'),'utf8');
const sources=[];
html=html.replace(/<script\b([^>]*)>([\s\S]*?)<\/script>/g,(_,attrs,inline)=>{
  const match=attrs.match(/\bsrc="([^"?]+)(?:\?[^"]*)?"/);
  if(match){
    const filename=path.resolve(source,match[1]);
    if(path.relative(source,filename).startsWith('..')||!filename.endsWith('.js'))throw Error('Unexpected startup script');
    sources.push('// '+match[1]+'\n'+fs.readFileSync(filename,'utf8'));
  }else if(inline.trim())sources.push(inline);
  return '';
});
if(sources.length<10)throw Error('Startup script list is incomplete');
const bundle=sources.join('\n;\n');
const hash=crypto.createHash('sha256').update(bundle).digest('hex').slice(0,12);
fs.mkdirSync(path.join(output,'assets'),{recursive:true});
fs.writeFileSync(path.join(output,'assets','app.'+hash+'.js'),bundle);
html=html.replace('<html lang="en-IE">','<html lang="en-IE" data-hosting="static">');
const error="document.getElementById('startup-message').textContent='The app could not load. Please reload.';document.getElementById('startup-retry').hidden=false";
html=html.replace('</body>','<script defer src="assets/app.'+hash+'.js" onerror="'+error+'"></script>\n</body>');
fs.writeFileSync(path.join(output,'index.html'),html);
fs.writeFileSync(path.join(output,'.nojekyll'),'');
fs.mkdirSync(path.join(output,'public'),{recursive:true});
fs.writeFileSync(path.join(output,'public','index.html'),'<!doctype html><meta charset="utf-8"><title>Brain Teaser</title><script>location.replace("../"+location.search+location.hash)</script><a href="../">Open Brain Teaser</a>');
console.log('Built dist: one versioned startup bundle ('+Buffer.byteLength(bundle)+' bytes), app root and legacy-link redirect.');
